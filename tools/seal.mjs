// Seals the chapter notes so that browsing the repo, a diff or a search does not show a chapter
// the player has not reached. The readable notes live in notes/chapters/*.json, which git ignores.
//
//   node tools/seal.mjs        notes/chapters/*.json  ->  data/chapters.js (checked, then sealed)
//   node tools/seal.mjs open   data/chapters.js       ->  notes/chapters/*.json (to edit them)

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { FACULTY } from '../data/faculty.js';
import { UNIT_BY_ID } from '../data/units.js';
import { CLASS_BY_NAME } from '../data/classes.js';
import { PARALOGUE_BY_ID } from '../data/paralogues.js';
import { SUPPORTS } from '../data/skills.js';
import { EQUIPMENT, ACCESSORY_ORDER } from '../data/accessories.js';

const AUTO_KEYS = new Set(['recruited', 'recruits', 'reached', 'mastered', 'support', 'paralogues', 'after', 'past']);
// The kinds the item list knows how to label (js/views/ui.js, ITEM_KIND).
const ITEM_KINDS = new Set(['relic', 'sacred', 'weapon', 'staff', 'shield', 'ring', 'gem', 'stat', 'seal', 'battalion', 'material', 'sell', 'skip']);

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const notesDir = path.join(root, 'notes', 'chapters');
const outFile = path.join(root, 'data', 'chapters.js');

const TAGS = new Set(['recrutar', 'classe', 'social', 'treino', 'paralogue', 'rota', 'info', 'batalha']);
const FACULTY_IDS = new Set([...FACULTY.map((f) => f.id), '*']);

const order = (key) => (key === 'p2' ? 99 : Number(key));

function check(note, file, seenIds) {
  const fail = (msg) => {
    throw new Error(`${file}: ${msg}`);
  };
  if (!note.key || !note.title) fail('precisa de key e title');
  for (const id of note.away ?? []) if (!FACULTY_IDS.has(id)) fail(`instrutor desconhecido em away: ${id}`);
  for (const t of note.tasks ?? []) {
    if (!t.id || !t.text) fail('tarefa sem id ou texto');
    if (!TAGS.has(t.tag)) fail(`tag desconhecida: ${t.tag}`);
    if (seenIds.has(t.id)) fail(`id de tarefa repetido: ${t.id}`);
    seenIds.add(t.id);
    if (t.auto) checkAuto(t, fail);
  }
  for (const it of note.items ?? []) {
    if (!it.item || !it.why) fail('item sem nome ou motivo');
    if (!ITEM_KINDS.has(it.kind)) fail(`item ${it.item}: tipo desconhecido ${it.kind}`);
    if (!Array.isArray(it.who)) fail(`item ${it.item}: who deve ser uma lista`);
    for (const id of it.who) if (!UNIT_BY_ID[id]) fail(`item ${it.item}: unidade desconhecida ${id}`);
    // One accessory per unit (js/logic.js, accessoryPlan): it has to know which items take the slot.
    if (['ring', 'shield', 'gem'].includes(it.kind) && !EQUIPMENT.has(it.item)) fail(`item ${it.item}: acessório fora de data/accessories.js`);
    if (EQUIPMENT.has(it.item) && !ACCESSORY_ORDER.includes(it.item)) fail(`item ${it.item}: falta em ACCESSORY_ORDER`);
  }
}

// The rule that settles a task by itself (js/logic.js, taskAuto). Every name has to exist.
function checkAuto(t, fail) {
  const where = `tarefa ${t.id}`;
  const unit = (id) => UNIT_BY_ID[id] || fail(`${where}: unidade desconhecida ${id}`);
  for (const key of Object.keys(t.auto)) if (!AUTO_KEYS.has(key)) fail(`${where}: regra desconhecida ${key}`);
  const a = t.auto;
  for (const id of a.recruited ?? []) unit(id);
  if (a.recruits && !['starters', 'all'].includes(a.recruits)) fail(`${where}: recruits deve ser starters ou all`);
  for (const map of [a.reached, a.mastered]) {
    for (const [id, cls] of Object.entries(map ?? {})) {
      unit(id);
      if (!CLASS_BY_NAME[cls]) fail(`${where}: classe desconhecida ${cls}`);
    }
  }
  for (const [id, rank] of Object.entries(a.support ?? {})) {
    unit(id);
    if (!SUPPORTS.includes(rank)) fail(`${where}: suporte ${rank} não aparece no jogo`);
  }
  for (const id of a.paralogues ?? []) if (!PARALOGUE_BY_ID[id]) fail(`${where}: paralogue desconhecido ${id}`);
  if (a.after && !/^\d{1,2}\/\d{1,2}$/.test(a.after)) fail(`${where}: after deve ser mês/dia`);
  if ('past' in a && a.past !== true) fail(`${where}: past deve ser true`);
}

async function seal() {
  const files = (await readdir(notesDir)).filter((f) => f.endsWith('.json'));
  const seen = new Set();
  const notes = [];
  for (const file of files) {
    const note = JSON.parse(await readFile(path.join(notesDir, file), 'utf8'));
    check(note, file, seen);
    notes.push(note);
  }
  notes.sort((a, b) => order(a.key) - order(b.key));
  const lines = notes.map((n) => `  '${n.key}': '${Buffer.from(JSON.stringify(n), 'utf8').toString('base64')}',`);
  const body = [
    '// Generated by tools/seal.mjs from notes/chapters/*.json. Do not edit by hand.',
    '// Each chapter is base64-sealed so the repo does not show what is ahead; the page opens only',
    '// the chapters the player has reached.',
    '',
    'export const SEALED = {',
    ...lines,
    '};',
    '',
  ].join('\n');
  await writeFile(outFile, body);
  console.log(`selados ${notes.length} capítulos → data/chapters.js`);
}

async function open() {
  const { SEALED } = await import(`../data/chapters.js?${Date.now()}`);
  await mkdir(notesDir, { recursive: true });
  for (const [key, b64] of Object.entries(SEALED)) {
    const note = JSON.parse(Buffer.from(b64, 'base64').toString('utf8'));
    const name = key === 'p2' ? 'p2.json' : `ch${key}.json`;
    await writeFile(path.join(notesDir, name), `${JSON.stringify(note, null, 2)}\n`);
  }
  console.log(`abertos ${Object.keys(SEALED).length} capítulos → notes/chapters/`);
}

await (process.argv[2] === 'open' ? open() : seal());
