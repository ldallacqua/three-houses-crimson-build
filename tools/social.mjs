// Rebuilds data/social.js (teas, tea topics, final-comment answers, liked meals, gifts) from
// fe3h.com: each character's page and the dining hall guide. Lysithea's teas, topics and answers
// were checked against Serenes Forest and match.
//
// The final comments themselves are game dialogue, so they are not published: the tool writes them
// to notes/tea-comments.json (ignored by git) and data/tea-gists.js keeps a short summary in
// Portuguese for each one, in the same order. If a character's comments change, the summaries
// have to be rewritten; the tests catch a count that no longer matches.
//
//   node tools/social.mjs

import { writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { UNITS } from '../data/units.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const UA = 'three-houses-crimson-build (github.com/ldallacqua/three-houses-crimson-build)';

async function get(url) {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'user-agent': UA }, signal: AbortSignal.timeout(60_000) });
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      return await res.text();
    } catch (err) {
      if (attempt >= 3) throw err;
    }
  }
}

const decode = (s) => s
  .replace(/<[^>]+>/g, '')
  .replace(/&#x27;|&#39;/g, "'")
  .replace(/&quot;/g, '"')
  .replace(/&amp;/g, '&')
  .replace(/&lt;/g, '<')
  .replace(/&gt;/g, '>')
  .replace(/\s+/g, ' ')
  .trim();

function nextData(page) {
  const m = page.match(/<script id="__NEXT_DATA__"[^>]*>([\s\S]*?)<\/script>/);
  return m ? JSON.parse(m[1]).props.pageProps : {};
}

/** The rows of the first table after `marker`, as arrays of cell texts (or cell link texts). */
function tableAfter(page, marker) {
  const at = page.indexOf(marker);
  if (at < 0) throw new Error(`no "${marker}" on the dining hall page`);
  const start = page.indexOf('<table', at);
  const table = page.slice(start, page.indexOf('</table>', start));
  return [...table.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)]
    .map((row) => [...row[1].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map((cell) => cell[1]))
    .filter((cells) => cells.length);
}

const names = (cell) => {
  const linked = [...cell.matchAll(/<a[^>]*>([\s\S]*?)<\/a>/g)].map((m) => decode(m[1])).filter(Boolean);
  return linked.length ? linked : decode(cell).split(',').map((s) => s.trim()).filter(Boolean);
};

const dining = await get('https://www.fe3h.com/monastery/dining_hall');
const MEALS = tableAfter(dining, 'listed in the following table').map(([meal, ingredients, category]) => ({
  name: decode(meal),
  ingredients: decode(ingredients).split(',').map((s) => s.trim()).filter(Boolean),
  category: decode(category),
}));
const likedBy = new Map(tableAfter(dining, 'List of Liked Meals').map(([meal, who]) => [decode(meal), names(who)]));
const dislikedBy = new Map(tableAfter(dining, 'List of Disliked Meals').map(([meal, who]) => [decode(meal), names(who)]));
if (MEALS.length < 30 || likedBy.size !== MEALS.length) throw new Error(`meal tables look wrong: ${MEALS.length} meals, ${likedBy.size} liked rows`);

// Spellings fe3h.com gets wrong in places, mapped to the item's name in the game.
const NAME_FIX = { 'Legend of Chivalry': 'Legends of Chivalry' };
const fix = (list = []) => list.map((n) => NAME_FIX[n] ?? n);

const SOCIAL = {};
const comments = {};
for (const unit of UNITS) {
  if (unit.id === 'byleth') continue;
  const data = nextData(await get(`https://www.fe3h.com/characters/${unit.id}`)).characterData;
  if (!data) throw new Error(`no data for ${unit.id}`);
  const first = data.name?.first ?? unit.name;
  const meals = (table) => MEALS.map((m) => m.name).filter((meal) => table.get(meal)?.includes(first));
  const tea = data.teatime ?? {};
  SOCIAL[unit.id] = {
    teas: tea.favoriteTeas ?? [],
    topics: [...(tea.topics ?? [])].sort((a, b) => a.localeCompare(b)),
    answers: (tea.finalComments ?? []).map((c) => c.validAnswers),
    meals: meals(likedBy),
    mealsDisliked: meals(dislikedBy),
    gifts: fix(data.gifts),
    lostItems: fix(data.lostItems),
  };
  comments[unit.id] = (tea.finalComments ?? []).map((c) => c.comment);
  console.log(`${unit.id}: ${SOCIAL[unit.id].teas.length} teas, ${SOCIAL[unit.id].topics.length} topics, ${comments[unit.id].length} comments, ${SOCIAL[unit.id].meals.length} meals`);
}

const header = `// Generated by tools/social.mjs from fe3h.com (character pages and the dining hall guide). Do not
// edit by hand: run the tool again. Topics are sorted; \`answers\` follows the order of the final
// comments, which data/tea-gists.js summarizes.
`;
await writeFile(path.join(root, 'data', 'social.js'),
  `${header}\nexport const MEALS = ${JSON.stringify(MEALS, null, 2)};\n\nexport const SOCIAL = ${JSON.stringify(SOCIAL, null, 2)};\n`);
await mkdir(path.join(root, 'notes'), { recursive: true });
await writeFile(path.join(root, 'notes', 'tea-comments.json'), `${JSON.stringify(comments, null, 2)}\n`);
console.log(`${MEALS.length} meals; wrote data/social.js and notes/tea-comments.json`);
